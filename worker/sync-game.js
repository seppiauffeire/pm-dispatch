// Copies the game data, combos and scoring engine out of ../index.html into src/game.js,
// so the server scores runs with exactly the same code the browser uses.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const html = fs.readFileSync(path.join(here, '..', 'index.html'), 'utf8').replace(/\r\n/g, '\n');
const a = html.indexOf('//DATA-START\n');
const endMark = '//ENGINE-END';
const b = html.indexOf(endMark);
if (a < 0 || b < 0) {
  console.error('Could not find the //DATA-START ... //ENGINE-END block in index.html');
  process.exit(1);
}
const body = html.slice(a, b + endMark.length);
const out =
  '// GENERATED by sync-game.js from ../index.html. Do not edit by hand. Run: npm run sync\n' +
  body +
  '\n\nexport { scoreRun, combosFor, PROBLEMS, NODES, COMBOS, START, BUDGET };\n';
fs.writeFileSync(path.join(here, 'src', 'game.js'), out);
console.log('Wrote src/game.js (' + out.length + ' bytes)');
